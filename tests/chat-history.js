// 消息回看必须保存原话，且不能把排队消息提前送达或重复触发剧情。
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const { resolve } = require('node:path');
const GAME = pathToFileURL(resolve(__dirname,'../index.html')).href;
const KEY = 'jingyuan-save-v2';

(async()=>{
  const browser=await chromium.launch();
  const errors=[];
  const game=async(save,width=1280)=>{
    const p=await browser.newPage({viewport:{width,height:844}});
    p.on('pageerror',e=>errors.push(e.message));
    await p.clock.install({time:new Date('2026-10-19T23:46:00Z')});
    await p.clock.pauseAt(new Date('2026-10-19T23:47:00Z'));
    await p.addInitScript(({key,save})=>{
      if(!localStorage.getItem(key))localStorage.setItem(key,JSON.stringify(save));
    },{key:KEY,save});
    await p.goto(GAME,{waitUntil:'domcontentloaded'});
    return p;
  };
  const state=p=>p.evaluate(key=>JSON.parse(localStorage.getItem(key)),KEY);
  const nav=async(p,url)=>{await p.fill('#addr',url);await p.press('#addr','Enter');};
  const history=async p=>{await p.click('#bHistory');assert.equal(await p.locator('.history').isVisible(),true);};
  const close=async p=>{await p.click('#historyClose');};
  try{
    const p=await game({notes:['start'],flags:{},seenIntro:true,doorFails:0,last:'xundu.com'});
    await nav(p,'jingyuan-miaopu.com');
    assert.equal((await state(p)).pendingPhones.length,1);
    assert.equal((await state(p)).phoneHistory.length,0);
    await history(p);
    await p.clock.fastForward(9000);
    assert.equal(await p.locator('[data-phone-record]').count(),0,'排队尚未送达的消息不出现在记录里');
    assert.equal((await state(p)).phoneHistory.length,0);
    assert.equal((await state(p)).flags.ph_jy1,undefined);
    await close(p);
    await p.clock.fastForward(1000);
    assert.equal(await p.locator('.toast').count(),1);
    assert.equal((await state(p)).phoneHistory.length,1);
    const unread=await state(p);
    await history(p);
    assert.equal(await p.locator('[data-phone-record]').count(),1);
    assert.equal((await state(p)).flags.ph_jy1,undefined,'回看不代替关闭原消息');
    assert.deepEqual((await state(p)).pendingPhones,unread.pendingPhones);
    await p.keyboard.press('Shift+Tab');
    assert.equal(await p.evaluate(()=>document.activeElement.tagName),'SUMMARY','键盘焦点留在记录对话框内');
    await p.keyboard.press('Escape');
    assert.equal(await p.evaluate(()=>document.activeElement.id),'bHistory');
    assert.equal(await p.locator('.toast').count(),1);
    await p.click('.toast .x');
    const read=await state(p);
    await history(p);await close(p);
    assert.deepEqual(await state(p),read,'回看不改变进度、队列或已读标记');
    await nav(p,'blog.xiaoman.me');
    await p.clock.fastForward(7000);
    assert.equal((await state(p)).phoneHistory.length,2);
    await p.reload({waitUntil:'domcontentloaded'});
    await p.clock.fastForward(7000);
    assert.equal((await state(p)).phoneHistory.length,2,'未读消息刷新重现不重复归档');
    await p.click('.toast .x');
    await history(p);
    assert.match(await p.locator('[data-phone-record]').first().innerText(),/我刚才趴在桌上/,'最近送达的消息排在前面');
    assert.equal(await p.locator('[data-phone-record]').first().getAttribute('open'),'');
    await close(p);
    p.once('dialog',d=>d.dismiss());await p.click('#bReset');
    assert.equal((await state(p)).phoneHistory.length,2,'取消重开保留消息记录');
    p.once('dialog',d=>d.accept());await p.click('#bReset');
    assert.deepEqual((await state(p)).phoneHistory,[]);
    await p.click('.phone header');await p.click('#goStart');
    await p.clock.fastForward(9000);
    await history(p);
    assert.equal(await p.locator('[data-phone-record]').count(),0,'重开清空旧记录且旧消息不再出现');
    await p.close();
    console.log('PASS: 送达才归档、刷新去重、最近优先、回看不改进度、键盘关闭与重开保护');

    const skipped=await game({notes:['start'],flags:{gardener:true},seenIntro:true,doorFails:0,last:'jingyuan-miaopu.com/gardener'});
    await skipped.fill('#d-code','0921');await skipped.press('#d-code','Enter');
    assert.equal((await state(skipped)).flags.ph_gd1,true);
    assert.equal((await state(skipped)).phoneHistory.length,0,'章节清理掉的未送达消息不能被记录冒充为已收到');
    await skipped.close();
    const gd=await game({notes:['start'],flags:{gardener:true},seenIntro:true,doorFails:0,last:'jingyuan-miaopu.com/gardener'});
    await gd.clock.fastForward(7000);
    await history(gd);await close(gd);
    assert.ok(!(await state(gd)).notes.includes('~2'),'回看不执行原消息关闭后的剧情');
    assert.equal((await state(gd)).flags.ph_gd1,undefined);
    await gd.click('.toast .x');
    assert.ok((await state(gd)).notes.includes('~2'));
    const after=await state(gd);
    await history(gd);await close(gd);
    assert.deepEqual(await state(gd),after);
    await gd.close();
    const song=await game({notes:['start'],flags:{ch2:true,g_he:true,g_xu:true,g_su:true,g_tang:true},seenIntro:true,doorFails:0,last:'space.qiancheng.net/songzhi'});
    await song.clock.fastForward(7000);
    await history(song);await close(song);
    assert.equal(await song.locator('.ending').count(),0,'回看宋芷消息不提前跳过章节');
    await song.click('.toast .x');
    assert.match(await song.locator('.ending h1').innerText(),/第三章/);
    await song.keyboard.press('Escape');
    assert.equal(await song.locator('#overlay').isVisible(),true,'记录的关闭事件不能泄漏到章节过场');
    await song.close();
    console.log('PASS: 原手机消息仍按原流程推进；回看不重复触发线索或章节');

    const legacy={notes:['start','letter'],flags:{ch2:true,ch3:true,end:'true',ph_jy1:true},seenIntro:true,doorFails:2,last:'xundu.com'};
    const m=await game(legacy,390);
    await m.click('#fab');await history(m);
    assert.equal(await m.locator('[data-phone-record]').count(),0,'不凭旧已读标记伪造未保存的原话');
    assert.equal((await state(m)).flags.end,'true');
    assert.equal((await state(m)).doorFails,2);
    assert.ok((await state(m)).notes.includes('letter'));
    await close(m);
    await m.close();
    const text='原话里的 <b>字样</b> 应当原样保留。';
    const small=await game({notes:['start'],flags:{},seenIntro:true,doorFails:0,last:'xundu.com',pendingPhones:[{id:'sample',who:'一位朋友',msgs:[text],unknown:true}]},390);
    await small.clock.fastForward(7000);
    await small.click('.toast .x');
    await small.click('#fab');await history(small);
    assert.equal(await small.locator('.history-chat .msg').innerText(),text);
    assert.equal(await small.locator('.history-chat .msg b').count(),0,'记录按文字显示，不解释为网页代码');
    for(const width of [320,390]){
      await small.setViewportSize({width,height:844});
      assert.equal(await small.evaluate(()=>document.documentElement.scrollWidth>innerWidth||document.querySelector('.history').scrollWidth>document.querySelector('.history').clientWidth),false);
    }
    await close(small);
    assert.equal(await small.locator('#fab').getAttribute('aria-expanded'),'true','回到调查后保留原来的笔记抽屉状态');
    await small.close();
    console.log('PASS: 旧存档保留进度；原话按文字显示；320/390px 记录窗口无横向溢出');
    assert.deepEqual(errors,[]);
    console.log('errors:',errors);
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
